from __future__ import annotations

from PySide6.QtCore import QLocale


LANGUAGE_MODES = ("system", "zh", "en")


def resolve_language_mode(mode: str | None) -> str:
    if mode not in LANGUAGE_MODES:
        mode = "system"
    if mode == "system":
        name = QLocale.system().name().lower()
        return "zh" if name.startswith("zh") else "en"
    return mode


def translate(mode: str | None, key: str, **kwargs) -> str:
    language = resolve_language_mode(mode)
    text = _TRANSLATIONS.get(language, _TRANSLATIONS["en"]).get(
        key,
        _TRANSLATIONS["en"].get(key, key),
    )
    return text.format(**kwargs)


